"""Regenerate the small SVG previews in the public geometry catalogue.

Run ``python tools/render_library_catalogue.py`` from the project environment.
Only GeomPype, its existing KLayout dependency and the standard library are
needed. Every preview comes from a real GDS build with COMSOL disabled. SVG
paths retain polygon holes, use equal x/y scaling and show local +y upward.
Each thumbnail is fitted independently; the catalogue states its dimensions.
"""

from html import escape
from pathlib import Path
from tempfile import TemporaryDirectory

import klayout.db as kdb

from geompype import Project
from geompype.library import (
    box_mark, cross_mark, l_mark, three_inch_wafer, vernier_mark, x_diamond_mark,
)


WIDTH, HEIGHT, MARGIN = 200, 160, 18
REFERENCE_COLOUR = '#2563eb'
MOVING_COLOUR = '#ea580c'
PREVIEWS = (
    ('x_diamond_mark', x_diamond_mark,
     'X and four diamond satellites; span 175.092 micrometres.'),
    ('cross_mark', cross_mark,
     'Centred cross; size 100 and arm width 10 micrometres.'),
    ('l_mark', l_mark,
     'L with arms along local +x and +y; size 100 and width 10 micrometres.'),
    ('box_mark', box_mark,
     'Square frame with a real hole; size 100 and wall width 10 micrometres.'),
    ('vernier_mark', vernier_mark,
     'Two rows of 11 ticks: blue reference below, orange moving layer above. '
     'Pitch 10, resolution 1, width 2, length 20 and gap 4 micrometres.'),
    ('wafer', three_inch_wafer,
     'Three-inch wafer, diameter 76.2 mm, with two flats. '
     'Primary flat at +y: 22.22 mm; secondary flat at -x: 11.18 mm.'),
)


def svg_preview(layout, title, description):
    """Draw the exported polygons, including holes, in a fixed thumbnail box."""
    cell = layout.top_cell()
    bounds = cell.bbox()
    scale = min((WIDTH - 2*MARGIN) / bounds.width(),
                (HEIGHT - 2*MARGIN) / bounds.height())
    centre_x = (bounds.left + bounds.right) / 2
    centre_y = (bounds.bottom + bounds.top) / 2

    def ring_path(points):
        coordinates = [f'{WIDTH/2 + (point.x-centre_x)*scale:.4f},'
                       f'{HEIGHT/2 - (point.y-centre_y)*scale:.4f}'
                       for point in points]
        return 'M ' + ' L '.join(coordinates) + ' Z'

    lines = [
        '<!-- Generated by tools/render_library_catalogue.py; edit the geometry, not this file. -->',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" '
        f'viewBox="0 0 {WIDTH} {HEIGHT}" role="img" aria-labelledby="title description">',
        f'  <title id="title">{escape(title)}</title>',
        f'  <desc id="description">{escape(description)}</desc>',
        f'  <rect width="{WIDTH}" height="{HEIGHT}" rx="8" fill="#ffffff"/>',
    ]
    for number, colour in ((1, REFERENCE_COLOUR), (2, MOVING_COLOUR)):
        layer = layout.find_layer(number, 0)
        if layer is None:
            continue
        region = kdb.Region(cell.begin_shapes_rec(layer)).merged()
        for polygon in region.each():
            rings = [ring_path(polygon.each_point_hull())]
            rings.extend(ring_path(polygon.each_point_hole(index))
                         for index in range(polygon.holes()))
            lines.append(f'  <path fill="{colour}" fill-rule="evenodd" d="{" ".join(rings)}"/>')
    lines.append('</svg>')
    return '\n'.join(lines) + '\n'


def render_catalogue(destination):
    """Build the six documented examples and write their vector thumbnails."""
    destination.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(prefix='geompype_catalogue_') as temporary:
        for name, factory, description in PREVIEWS:
            project = Project(output=Path(temporary)/name)
            reference = project.add_layer('reference', gds_layer=1, comsol=False)
            if name == 'vernier_mark':
                moving = project.add_layer('moving', gds_layer=2, comsol=False)
                factory(project, reference_layer=reference, moving_layer=moving)
            elif name == 'wafer':
                factory(project, layer=reference, flats=2)
            else:
                factory(project, layer=reference)
            project.build()
            layout = kdb.Layout()
            layout.read(str(project.gds_path))
            target = destination/f'{name}.svg'
            target.write_text(svg_preview(layout, factory.__name__, description),
                              encoding='utf-8', newline='\n')
            print(f'Wrote {target.name}')


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    render_catalogue(root/'docs/images/library')
